use std::env;
use std::fs;
use std::io::BufWriter;
use std::path::{Path, PathBuf};

fn main() {
    emit_piece_sprites();
}

/// Decode `assets/piece/*.png` into static RGBA byte arrays under OUT_DIR.
fn emit_piece_sprites() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let piece_dir = manifest_dir.join("assets/piece");

    const PIECES: &[(&str, &str)] = &[
        ("WHITE", "PAWN"),
        ("WHITE", "KNIGHT"),
        ("WHITE", "BISHOP"),
        ("WHITE", "ROOK"),
        ("WHITE", "QUEEN"),
        ("WHITE", "KING"),
        ("BLACK", "PAWN"),
        ("BLACK", "KNIGHT"),
        ("BLACK", "BISHOP"),
        ("BLACK", "ROOK"),
        ("BLACK", "QUEEN"),
        ("BLACK", "KING"),
    ];

    let dest = out_dir.join("piece_sprites.rs");
    let mut out = BufWriter::new(fs::File::create(&dest).expect("create piece_sprites.rs"));

    use std::io::Write;
    writeln!(
        out,
        "// @generated by build.rs from assets/piece/*.png — do not edit.\n\
         \n\
         pub struct Sprite {{\n\
         \x20   pub width: u32,\n\
         \x20   pub height: u32,\n\
         \x20   /// RGBA8, row-major, non-premultiplied. Length is `width * height * 4`.\n\
         \x20   pub rgba: &'static [u8],\n\
         }}\n"
    )
    .unwrap();

    for (color, kind) in PIECES {
        let file_name = format!(
            "{}_{}.png",
            color.to_lowercase(),
            kind.to_lowercase()
        );
        let path = piece_dir.join(&file_name);
        println!("cargo:rerun-if-changed={}", path.display());

        let (width, height, rgba) = decode_png_rgba8(&path);
        let const_name = format!("{color}_{kind}");

        write!(out, "pub const {const_name}: Sprite = Sprite {{\n    width: {width},\n    height: {height},\n    rgba: &[\n").unwrap();
        for (i, byte) in rgba.iter().enumerate() {
            if i % 24 == 0 {
                write!(out, "        ").unwrap();
            }
            write!(out, "{byte},").unwrap();
            if i % 24 == 23 || i + 1 == rgba.len() {
                writeln!(out).unwrap();
            } else {
                write!(out, " ").unwrap();
            }
        }
        writeln!(out, "    ],\n}};\n").unwrap();
    }

    writeln!(
        out,
        "/// Look up an embedded piece sprite. `color`: 0 = white, 1 = black. `kind`: 1..=6 (Pawn..King).\n\
         pub fn sprite(color: u8, kind: u8) -> Option<&'static Sprite> {{\n\
         \x20   match (color, kind) {{\n\
         \x20       (0, 1) => Some(&WHITE_PAWN),\n\
         \x20       (0, 2) => Some(&WHITE_KNIGHT),\n\
         \x20       (0, 3) => Some(&WHITE_BISHOP),\n\
         \x20       (0, 4) => Some(&WHITE_ROOK),\n\
         \x20       (0, 5) => Some(&WHITE_QUEEN),\n\
         \x20       (0, 6) => Some(&WHITE_KING),\n\
         \x20       (1, 1) => Some(&BLACK_PAWN),\n\
         \x20       (1, 2) => Some(&BLACK_KNIGHT),\n\
         \x20       (1, 3) => Some(&BLACK_BISHOP),\n\
         \x20       (1, 4) => Some(&BLACK_ROOK),\n\
         \x20       (1, 5) => Some(&BLACK_QUEEN),\n\
         \x20       (1, 6) => Some(&BLACK_KING),\n\
         \x20       _ => None,\n\
         \x20   }}\n\
         }}\n"
    )
    .unwrap();
}

fn decode_png_rgba8(path: &Path) -> (u32, u32, Vec<u8>) {
    let file = fs::File::open(path)
        .unwrap_or_else(|err| panic!("open {}: {err}", path.display()));
    let mut decoder = png::Decoder::new(file);
    decoder.set_transformations(
        png::Transformations::EXPAND | png::Transformations::ALPHA | png::Transformations::STRIP_16,
    );
    let mut reader = decoder
        .read_info()
        .unwrap_or_else(|err| panic!("read info {}: {err}", path.display()));
    let mut buf = vec![0u8; reader.output_buffer_size()];
    let info = reader
        .next_frame(&mut buf)
        .unwrap_or_else(|err| panic!("decode {}: {err}", path.display()));

    let width = info.width;
    let height = info.height;
    let raw = &buf[..info.buffer_size()];

    let rgba = match info.color_type {
        png::ColorType::Rgba => raw.to_vec(),
        png::ColorType::Rgb => {
            let mut out = Vec::with_capacity(width as usize * height as usize * 4);
            for px in raw.chunks_exact(3) {
                out.extend_from_slice(&[px[0], px[1], px[2], 255]);
            }
            out
        }
        png::ColorType::GrayscaleAlpha => {
            let mut out = Vec::with_capacity(width as usize * height as usize * 4);
            for px in raw.chunks_exact(2) {
                out.extend_from_slice(&[px[0], px[0], px[0], px[1]]);
            }
            out
        }
        png::ColorType::Grayscale => {
            let mut out = Vec::with_capacity(width as usize * height as usize * 4);
            for &g in raw {
                out.extend_from_slice(&[g, g, g, 255]);
            }
            out
        }
        png::ColorType::Indexed => {
            panic!(
                "{}: indexed PNG should have been expanded by Transformations::EXPAND",
                path.display()
            )
        }
    };

    let expected = width as usize * height as usize * 4;
    assert_eq!(
        rgba.len(),
        expected,
        "{}: unexpected RGBA length after decode",
        path.display()
    );
    (width, height, rgba)
}

